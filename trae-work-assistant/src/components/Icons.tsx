import type { ReactNode } from "react";

/**
 * 统一线性图标集：currentColor 描边、1.75 线宽，视觉重量一致。
 *
 * 旧版把图标写成 `const ic = (d: string) => ...` 的字符串拼接（`App.tsx` 里 4 个），
 * 页面里又各自内联 `<svg>`（接管页的清空按钮）。结果是同一枚「齿轮」在两处
 * 线宽不同、同一枚「垃圾桶」写法不同 —— 图标是最容易悄悄分叉的一类资产，
 * 所以它必须是一个集中可枚举的集合，而不是散落的字符串。
 */
type IconProps = { size?: number; className?: string };

function Svg({
  size = 18,
  className,
  children,
}: IconProps & { children: ReactNode }) {
  return (
    <svg
      className={className}
      width={size}
      height={size}
      viewBox="0 0 24 24"
      fill="none"
      stroke="currentColor"
      strokeWidth={1.75}
      strokeLinecap="round"
      strokeLinejoin="round"
      aria-hidden="true"
    >
      {children}
    </svg>
  );
}

